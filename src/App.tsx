/**
 * Screen-reader channel for toasts.
 *
 * Keeps the newest toast's message rendered even after it leaves the visual
 * queue, so a polite live region never announces an "empty" deletion. The
 * keyed span is replaced on each new toast, guaranteeing a fresh
 * announcement even when two toasts carry identical text.
 */
function ToastAnnouncer({ toasts }: { toasts: UiToast[] }) {
  const latest = toasts.length > 0 ? toasts[toasts.length - 1] : null;
  const [held, setHeld] = useState<{ id: number; message: string } | null>(null);
  useEffect(() => {
    if (latest && latest.id !== held?.id) setHeld(latest);
  }, [latest, held]);
  return (
    <div aria-live="polite" aria-atomic="true" className="sr-only">
      {held && <span key={held.id}>{held.message}</span>}
    </div>
  );
}

/**
 * /hotels/checkout serves two shapes of visit: a fresh reservation (the whole
 * window in the URL) and a booked one, reached again by reference from
 * "my stays". The same URL, distinguished by the `ref` param — so a
 * confirmation link is shareable and survives a refresh.
 */
function StayCheckoutViewWrapper({ onBooked }: { onBooked: (ref: string) => void }) {
  const { currentParams, navigateTo } = useTrip();
  const stayRef = currentParams.stayRef;

  if (stayRef) {
    return (
      <StayConfirmationView
        bookingRef={stayRef}
        onBack={() => navigateTo('/hotels')}
      />
    );
  }

  const slug = currentParams.accommodationSlug;
  const roomTypeId = currentParams.roomTypeId;
  if (!slug || !roomTypeId || !currentParams.checkIn || !currentParams.checkOut) {
    return (
      <StayConfirmationView
        bookingRef=""
        onBack={() => navigateTo('/hotels')}
      />
    );
  }

  return (
    <StayCheckoutView
      params={{
        accommodationSlug: slug,
        roomTypeId,
        checkIn: currentParams.checkIn,
        checkOut: currentParams.checkOut,
        rooms: currentParams.rooms ?? 1,
        adults: currentParams.adults ?? 2,
        children: currentParams.children ?? 0,
      }}
      onBack={() => navigateTo('/hotels', { hotelSlug: slug })}
      onBooked={onBooked}
    />
  );
}

