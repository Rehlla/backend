import { readFileSync, writeFileSync, existsSync } from 'fs';
import { execSync } from 'child_process';

const REGISTRY = 'src/shared/placeholderImagery.ts';
const registrySrc = readFileSync(REGISTRY, 'utf8');

const files = execSync('git ls-files --cached --others --exclude-standard "src/**/*.tsx" "src/**/*.ts"', {
  encoding: 'utf8'
})
  .split('\n')
  .filter(Boolean)
  .map((f) => f.replace(/\\/g, '/'))
  .filter((f) => existsSync(f))
  .filter((f) => !f.includes('placeholderImagery'));

const used = new Set<string>();
for (const f of files) {
  for (const m of readFileSync(f, 'utf8').matchAll(/IMG_P[A-Za-z0-9_]+/g)) used.add(m[0]);
}
const missing = [...used].filter((n) => !registrySrc.includes(`export const ${n}`));

// Derive the photo id + params from the constant name: IMG_P<id>_<suffix>
// where suffix is HERO (w=1600), CARD (w=800), or a numeric width.
const lines: string[] = [];
for (const name of missing) {
  const m = name.match(/^IMG_P(.+)_(HERO|CARD|\d{3,4})$/);
  if (!m) {
    console.error(`Cannot parse constant name: ${name}`);
    continue;
  }
  const [, id, suffix] = m;
  const width = suffix === 'HERO' ? 1600 : suffix === 'CARD' ? 800 : suffix;
  lines.push(
    `/** Placeholder — photo-${id}, generated by scripts/codemod-unsplash-registry.ts. */\nexport const ${name} = \`https://images.unsplash.com/photo-${id}?q=80&w=${width}&auto=format&fit=crop\`;`
  );
}

if (lines.length) {
  writeFileSync(REGISTRY, registrySrc.trimEnd() + '\n\n// --- Generated by codemod-unsplash-registry (photo-id-keyed constants) ---\n\n' + lines.join('\n\n') + '\n');
  console.log(`Appended ${lines.length} constant(s) to ${REGISTRY}`);
} else {
  console.log('Nothing to append.');
}
